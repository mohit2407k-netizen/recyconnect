bool paymentReceived = false;
@override
void initState() {
  super.initState();

  final String? lotId = widget.lot?['lotId']?.toString();
createPaymentDocument();
  if (lotId != null && lotId.isNotEmpty) {
    paymentSubscription = FirebaseFirestore.instance
        .collection('payments')
        .doc(lotId)
        .snapshots()
        .listen((snapshot) {
      final data = snapshot.data();

      if (data == null) return;

      final String status =
          data['status']?.toString().toLowerCase() ?? '';

      if (status == 'paid') {
        if (mounted) {
          setState(() {
            paymentReceived = true;
            paymentSubmitted = true;
          });
        }
      }
    });
  }
}
Future<void> createPaymentDocument() async {
  final String? lotId = widget.lot?['lotId']?.toString();

  if (lotId == null || lotId.isEmpty) return;

  final paymentRef =
      FirebaseFirestore.instance.collection('payments').doc(lotId);

  final existingPayment = await paymentRef.get();

  // Don't overwrite an existing payment status.
  if (existingPayment.exists) return;

  await paymentRef.set({
    'lotId': lotId,
    'amount': widget.amount,
    'status': 'pending',
    'recycler': widget.recyclerName,
    'collectorUpiId': widget.lot?['collectorUpiId']?.toString() ?? '',
    'createdAt': FieldValue.serverTimestamp(),
  });
}

