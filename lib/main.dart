Future<void> speakText(String english, String hindi) async {
  String text;

  // Get text according to selected app language
  if (selectedLanguage == 'हिन्दी') {
    text = hindi;
  } else {
    text = tr(english, hindi);
  }

  String languageCode;

  switch (selectedLanguage) {
    case 'हिन्दी':
      languageCode = 'hi-IN';
      break;

    case 'English':
      languageCode = 'en-IN';
      break;

    case 'मराठी':
      languageCode = 'mr-IN';
      break;

    case 'বাংলা':
      languageCode = 'bn-IN';
      break;

    case 'తెలుగు':
      languageCode = 'te-IN';
      break;

    case 'தமிழ்':
      languageCode = 'ta-IN';
      break;

    case 'ಕನ್ನಡ':
      languageCode = 'kn-IN';
      break;

    case 'ગુજરાતી':
      languageCode = 'gu-IN';
      break;

    case 'ਪੰਜਾਬੀ':
      languageCode = 'pa-IN';
      break;

    case 'اردو':
      languageCode = 'ur-IN';
      break;

    default:
      languageCode = 'en-IN';
  }

  try {
    await flutterTts.stop();

    await flutterTts.setLanguage(languageCode);

    await flutterTts.setSpeechRate(0.45);
    await flutterTts.setVolume(1.0);
    await flutterTts.setPitch(1.0);

    await flutterTts.speak(text);
  } catch (e) {
    debugPrint('TTS Error: $e');
  }
}
